# -*- coding: utf-8 -*-
"""
Сравнение названий событий и имен людей - одно правило для всех агентов.

Зачем отдельный файл: одно и то же событие приходит из разных источников под
разными названиями, и сверять их приходится в двух местах - в правиле «разбор
не повторяется» (агент 5) и при склейке дублей между своим сбором и городской
афишей (публикатор). Правило должно быть одно, иначе оно расходится и повторы
пролезают.

Случаи из жизни, которые правило обязано ловить:
  «Траектории интервалов» и «Выставка «Траектории интервалов»»;
  «Стеклянный зверинец» и «Стеклянный зверинец. Спектакль в кинотеатре»;
  «Фокус: Перформанс» и «Выставка «Фокус: Перформанс» в MYTH».
"""

import re

# Слова-типы, которыми источники начинают название: у нас «Траектории
# интервалов», в афише города «Выставка «Траектории интервалов»».
TYPE_WORDS = ("выставка", "экскурсия", "лекция", "спектакль", "фестиваль",
              "мастер класс", "мастеркласс", "перформанс", "показ", "кинопоказ",
              "концерт", "презентация", "встреча", "инсталляция", "экспозиция")

# Короткие названия по вхождению не сверяем - слишком легко слепить разное.
MIN_LEN = 12


def norm(s):
    """Привести строку к сравнимому виду: без кавычек, знаков и лишних пробелов."""
    s = str(s or "").lower().replace("ё", "е")
    s = re.sub(r"[«»\"'’„“]", " ", s)
    s = re.sub(r"[^\w\s]", " ", s, flags=re.UNICODE)
    return re.sub(r"\s+", " ", s).strip()


def strip_type(title):
    """Убрать зачин вида «выставка ...», если после него остается само название.
    Порог длины нужен, чтобы «Лекция о шрифте» не превратилась в «о шрифте»."""
    t = str(title or "").strip()
    for w in TYPE_WORDS:
        if t.startswith(w + " ") and len(t) - len(w) - 1 >= MIN_LEN:
            return t[len(w) + 1:].strip()
    return t


def key(title):
    """Сравнимый вид названия: приведено и без зачина-типа."""
    return strip_type(norm(title))


def same_title(title_a, title_b):
    """Одно ли это название: совпало целиком либо короткое вошло в длинное."""
    a, b = key(title_a), key(title_b)
    if not a or not b:
        return False
    if a == b:
        return True
    short, long_ = sorted((a, b), key=len)
    return len(short) >= MIN_LEN and short in long_


def same_event(title_a, venue_a, title_b, venue_b):
    """Одно ли это событие: площадка совпала и название совпало.
    Даты в сравнение НЕ входят - у длинной выставки они сдвигаются."""
    va, vb = norm(venue_a), norm(venue_b)
    if not va or va != vb:
        return False
    return same_title(title_a, title_b)


# ---------- имена людей ----------

# Слова, которые не различают людей: приставки, звания, инициалы.
NAME_NOISE = {"им", "имени", "художник", "художница", "автор", "куратор",
              "архитектор", "дизайнер", "фотограф", "скульптор"}


def name_words(name):
    """Различающие слова имени: без инициалов, званий и мелких частиц."""
    words = re.findall(r"[\w-]{3,}", norm(name))
    return {w for w in words if w not in NAME_NOISE}


# Окончания фамилий. Нужны, чтобы по одному слову сверять только фамилию:
# «Пушницкий» - это тот же человек, что «Виталий Пушницкий», а «Елена» - нет,
# потому что Елен в городе много.
SURNAME_ENDINGS = ("ов", "ев", "ёв", "ин", "ын", "ский", "цкий", "ской", "кой",
                   "ова", "ева", "ёва", "ина", "ына", "ская", "цкая", "их", "ых",
                   "ко", "ян", "енко", "дзе", "швили", "ук", "юк", "ай", "ер")


def looks_like_surname(word):
    return len(word) >= 5 and str(word).endswith(SURNAME_ENDINGS)


def same_person(name_a, name_b):
    """Один ли это человек. Имя приходит из разных источников по-разному:
    «Виталий Пушницкий», «Пушницкий Виталий», просто «Пушницкий». Поэтому
    сверяем набор слов без учета порядка: совпал целиком или один набор вложен
    в другой. Одиночное слово принимаем только если оно похоже на фамилию -
    иначе «Елена» слепится с любой Еленой, а «Сергей Бугаев» с «Сергей Иванов»."""
    a, b = name_words(name_a), name_words(name_b)
    if not a or not b:
        return False
    if a == b:
        return True
    if not (a <= b or b <= a):
        return False
    short = a if len(a) <= len(b) else b
    if len(short) == 1:
        return looks_like_surname(next(iter(short)))
    return any(len(w) >= 5 for w in (a & b))
